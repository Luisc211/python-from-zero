#Operadores aritméticos
#Suma y resta (+ y -)
suma = 5 + 3
resta = 5 - 3

#Multiplicación y división (* y /)
multiplicacion = 5 * 3
division = 5 / 3 #Devuelve un float(dato flotante)

#Potenciación o exponente (**)
potencia = 5 ** 3 #5 elevado a la 3

#División baja o floor division (//)
division_baja = 5 // 3 #Devuelve un entero redondeado hacia abajo

#resto o módulo (%)
resto = 5 % 3 #Devuelve el resto de la división

print("Suma: ", suma)
print("Resta: ", resta) 
print("Multiplicación: ", multiplicacion)
print("División: ", division)
print("Potencia: ", potencia)
print("División baja: ", division_baja)
print("Resto: ", resto)