#Operadores de comparación
#Los operadores de comparación se utilizan para comparar dos valores y devuelven un valor booleano
# ==, !=, >, <, >=, <=

igual = 5 == 6 #False
diferente = 5 != 6 #True
mayor_que = 5 > 6 #False
menor_que = 5 < 6 #True
mayor_o_igual = 5 >= 6 #False
menor_o_igual = 5 <= 6 #True


a = 10
b = 15
c = 20
comparacion = a + b == c
print("Comparación: ", comparacion) #False, ya que 10 + 15 = 25, que no es igual a 20

print("Igual: ", igual)
print("Diferente: ", diferente) 
print("Mayor que: ", mayor_que)
print("Menor que: ", menor_que) 
print("Mayor o igual: ", mayor_o_igual)
print("Menor o igual: ", menor_o_igual)
